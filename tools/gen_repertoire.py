"""Generate _repertoire.py from unicodedata2 18.0.0 (YP §4.4, specs.md §3)."""

import hashlib
from pathlib import Path
import sys
import unicodedata2

EXPECTED_VERSION = "18.0.0"
EXPECTED_NON_CN_COUNT = 312389
EXPECTED_NON_CN_RANGES = 735
EXPECTED_CANARY_SHA256 = "ea751092fc5e12e3b98f5538ad297624a500e38f6c756ac7ad974d05ff1baf86"

OUT_PATH = Path(__file__).resolve().parent.parent / "src" / "aethel_codex" / "_repertoire.py"


def main() -> int:
    if unicodedata2.unidata_version != EXPECTED_VERSION:
        sys.stderr.write(
            f"ERROR: unicodedata2 version {unicodedata2.unidata_version} != {EXPECTED_VERSION}\n"
        )
        return 1

    non_cn_ranges: list[tuple[int, int]] = []
    cn_ranges: list[tuple[int, int]] = []

    start_non_cn: int | None = None
    start_cn: int | None = None
    count_non_cn = 0
    count_cn = 0

    for cp in range(0x110000):
        cat = unicodedata2.category(chr(cp))
        if cat != "Cn":
            count_non_cn += 1
            if start_non_cn is None:
                start_non_cn = cp
            if start_cn is not None:
                cn_ranges.append((start_cn, cp - 1))
                start_cn = None
        else:
            count_cn += 1
            if start_cn is None:
                start_cn = cp
            if start_non_cn is not None:
                non_cn_ranges.append((start_non_cn, cp - 1))
                start_non_cn = None

    if start_non_cn is not None:
        non_cn_ranges.append((start_non_cn, 0x10FFFF))
    if start_cn is not None:
        cn_ranges.append((start_cn, 0x10FFFF))

    # Calculate canary SHA-256
    lines = [f"{s:04X}-{e:04X}" for s, e in non_cn_ranges]
    canary_bytes = "\n".join(lines).encode("ascii")
    canary_sha256 = hashlib.sha256(canary_bytes).hexdigest()

    assert count_non_cn == EXPECTED_NON_CN_COUNT, (count_non_cn, EXPECTED_NON_CN_COUNT)
    assert len(non_cn_ranges) == EXPECTED_NON_CN_RANGES, (
        len(non_cn_ranges),
        EXPECTED_NON_CN_RANGES,
    )
    assert canary_sha256 == EXPECTED_CANARY_SHA256, (canary_sha256, EXPECTED_CANARY_SHA256)

    content = f'''"""Generated repertoire table for Unicode {EXPECTED_VERSION} (auto-generated by tools/gen_repertoire.py).

Do not edit by hand.
"""

UNICODE_VERSION: str = "{EXPECTED_VERSION}"
CANARY_SHA256: str = "{canary_sha256}"
NON_CN_COUNT: int = {count_non_cn}
NON_CN_RANGES_COUNT: int = {len(non_cn_ranges)}
CN_COUNT: int = {count_cn}
CN_RANGES_COUNT: int = {len(cn_ranges)}

# Ranges (start, end inclusive) of non-Cn scalars (assigned, private-use, surrogates, controls)
NON_CN_RANGES: tuple[tuple[int, int], ...] = (
'''
    for s, e in non_cn_ranges:
        content += f"    (0x{s:06X}, 0x{e:06X}),\n"
    content += ")\n\n# Ranges (start, end inclusive) of unassigned scalars (General_Category == Cn)\nCN_RANGES: tuple[tuple[int, int], ...] = (\n"
    for s, e in cn_ranges:
        content += f"    (0x{s:06X}, 0x{e:06X}),\n"
    content += ")\n"

    OUT_PATH.write_text(content, encoding="utf-8")
    print(
        f"Generated {OUT_PATH} successfully ({len(non_cn_ranges)} non-Cn ranges, {len(cn_ranges)} Cn ranges)."
    )
    print(f"Canary SHA-256: {canary_sha256}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
